"""config/positions.ltx [pos_dlc2]: world positions of the Dragonborn (Solstheim) locations. Their world marker references do not resolve at
runtime until Solstheim is loaded, so the positions are read here from the user's own Dragonborn.esm: the location's marker reference,
or the centroid of the exterior cells that name the location (or one of its children).
Keys are Dragonborn-local FormIDs (the plugin maps runtime IDs to them, so the file does not depend on load order).

usage: python gen_positions_dlc.py   (rewrites the [pos_dlc2] section of ../config/positions.ltx)"""
import os, struct, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import esp

D = os.environ.get("SKYRIM_DIR", "C:/Program Files (x86)/Steam/steamapps/common/Skyrim Special Edition") + "/Data/"
buf = esp.load(D + "Dragonborn.esm")
OWN = 2                                   # Dragonborn.esm's own master index in its FormIDs (two masters before it)
SOLSTHEIM = (OWN << 24) | 0x800           # DLC2SolstheimWorld

lctn, wrld = {}, {}
for r in esp.walk(buf):
    if r.sig == "LCTN":
        L = dict(edid="", parent=0, marker=0)
        for s, d in r.subs():
            if s == "EDID": L["edid"] = esp.zstr(d)
            elif s == "PNAM": L["parent"] = struct.unpack("<I", d)[0]
            elif s == "MNAM": L["marker"] = struct.unpack("<I", d)[0]
        lctn[r.fid] = L
    elif r.sig == "WRLD":
        W = dict(edid="", parent=0)
        for s, d in r.subs():
            if s == "EDID": W["edid"] = esp.zstr(d)
            elif s == "WNAM": W["parent"] = struct.unpack("<I", d)[0]
        wrld[r.fid] = W


def root_world(w):
    for _ in range(8):
        if w in wrld and wrld[w]["parent"]: w = wrld[w]["parent"]
        else: break
    return w


cellpos = {}   # location -> [(x, y, world)]
for r in esp.walk(buf):
    if r.sig != "CELL": continue
    world = 0
    for gt, lbl in r.group_path:
        if gt == 1: world = lbl
    if not world: continue
    xclc = xlcn = None
    for s, d in r.subs():
        if s == "XCLC" and len(d) >= 8: xclc = struct.unpack_from("<ii", d, 0)
        elif s == "XLCN" and len(d) >= 4: xlcn = struct.unpack_from("<I", d, 0)[0]
    if xclc and xlcn: cellpos.setdefault(xlcn, []).append((xclc[0] * 4096 + 2048, xclc[1] * 4096 + 2048, world))

want = {L["marker"]: f for f, L in lctn.items() if L["marker"]}
mpos = {}
for r in esp.walk(buf):
    if r.sig == "REFR" and r.fid in want:
        world = 0
        for gt, lbl in r.group_path:
            if gt == 1: world = lbl
        for s, d in r.subs():
            if s == "DATA" and len(d) >= 12:
                x, y, z = struct.unpack_from("<3f", d, 0)
                mpos[r.fid] = (x, y, world)


def descendants(f):
    res = [f]
    for k, L in lctn.items():
        if L["parent"] == f: res += descendants(k)
    return res


rows = []
for f, L in lctn.items():
    if (f >> 24) != OWN: continue                    # only locations this plugin defines
    if L["marker"] in mpos:
        x, y, w = mpos[L["marker"]]
    else:
        pts = []
        for d in descendants(f): pts += cellpos.get(d, [])
        if not pts: continue
        x = sum(p[0] for p in pts) / len(pts); y = sum(p[1] for p in pts) / len(pts); w = pts[0][2]
    if root_world(w) != SOLSTHEIM: continue
    if any(k in L["edid"] for k in ("Apo", "HoldingCell", "Virtual", "POI", "Dummy", "AmbushCell")): continue   # Apocrypha, holding cells, point-of-interest markers
    rows.append((f & 0xFFFFFF, x, y, L["edid"].replace("Location", "")))
rows.sort()

path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "config", "positions.ltx")
text = open(path, encoding="utf-8", newline="").read()
nl = "\r\n" if "\r\n" in text else "\n"
head = text.split("[pos_dlc2]")[0].rstrip() + nl
sec = nl.join(["", "; Dragonborn (Solstheim) locations: Dragonborn.esm local FormID = x, y. Generated by tools/gen_positions_dlc.py.", "[pos_dlc2]"] +
              [f"{fid:X} = {x:.0f}, {y:.0f}   ; {n}" for fid, x, y, n in rows]) + nl
open(path, "w", encoding="utf-8", newline="").write(head + sec)
print(len(rows), "Solstheim positions written")
for fid, x, y, n in rows[:12]: print(f"  {fid:X} {x:.0f},{y:.0f} {n}")
