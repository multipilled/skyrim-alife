"""config/water.ltx: locations next to open water (a cell in the 3x3 neighbourhood has a real water level and the location's marker
sits within ~1200 units of it). Derived from XCLW in the user's Skyrim.esm. Fishing spots in the sim."""
import sys, struct, json, os
here = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, here)
import esp
buf = esp.load(os.environ.get("SKYRIM_DIR", "C:/Program Files (x86)/Steam/steamapps/common/Skyrim Special Edition") + "/Data/Skyrim.esm")
water = {}
for r in esp.walk(buf):
    if r.sig != "CELL": continue
    world = 0
    for gt, lbl in r.group_path:
        if gt == 1: world = lbl
    if world != 0x3C: continue
    xclc = xclw = None
    for s, d in r.subs():
        if s == "XCLC" and len(d) >= 8: xclc = struct.unpack_from("<ii", d, 0)
        elif s == "XCLW": xclw = struct.unpack("<f", d[:4])[0]
    if xclc and xclw is not None and -50000 < xclw < 50000: water[xclc] = xclw
d = json.load(open(os.path.join(here, "..", "..", "data", "world_skyrim.json")))
rows = []
for L in d["locations"]:
    if L["root_world"] != 0x3C or 0x16771 in L["keywords"]: continue
    cx, cy = int(L["x"] // 4096), int(L["y"] // 4096)
    best = None
    for dx in (-1, 0, 1):
        for dy in (-1, 0, 1):
            h = water.get((cx + dx, cy + dy))
            if h is None: continue
            if L.get("source_pos") == "marker" and abs(L["z"] - h) > 1200: continue
            best = h if best is None else best
    if best is not None: rows.append((L["formid"], best, L["edid"].replace("Location", "")))
rows.sort()
out = ["; Locations beside open water (fishing spots). FormID = water level. Generated by tools/gen_water.py from the cell water heights.", "[water]"]
for fid, h, n in rows: out.append(f"{fid:X} = {h:.0f}   ; {n}")
open(os.path.join(here, "..", "config", "water.ltx"), "w", newline="\n").write("\n".join(out) + "\n")
print(len(water), "water cells;", len(rows), "waterside locations")
