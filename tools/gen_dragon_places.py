"""Writes config/dragon_places.ltx: the locations that hold a word wall (WordWallTrigger ACTI 0x05095E), the places dragons
visit besides their lairs (docs/DRAGONS.md section 4). Reads Skyrim.esm read-only.
usage: python gen_dragon_places.py [Skyrim.esm] [out.ltx]"""
import os, struct, sys
import esp

WORD_WALL = 0x05095E
SKIP = {0x3444E, 0xE9DA7}   # DarkBrotherhoodSanctuary, Warehouse: not dragon country (docs/DRAGONS.md)
here = os.path.dirname(os.path.abspath(__file__))
src = sys.argv[1] if len(sys.argv) > 1 else os.environ.get("SKYRIM_DIR", "C:/Program Files (x86)/Steam/steamapps/common/Skyrim Special Edition") + "/Data/Skyrim.esm"
out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(here, "..", "config", "dragon_places.ltx")

buf = esp.load(src)
cell_loc, loc_name, walls = {}, {}, []
for r in esp.walk(buf):
    if r.sig == "CELL":
        for sig, d in r.subs():
            if sig == "XLCN" and len(d) >= 4: cell_loc[r.fid] = struct.unpack_from("<I", d)[0]
    elif r.sig == "LCTN":
        for sig, d in r.subs():
            if sig == "EDID": loc_name[r.fid] = esp.zstr(d)
    elif r.sig == "REFR":
        subs = dict(r.subs())
        if "NAME" in subs and struct.unpack_from("<I", subs["NAME"])[0] == WORD_WALL:
            parent = next((lbl for gtype, lbl in reversed(r.group_path) if gtype in (8, 9, 10)), None)
            walls.append((r.fid, parent))

locs, unplaced = {}, 0
for fid, cell in walls:
    loc = cell_loc.get(cell)
    if not loc: unplaced += 1; continue
    if loc in SKIP: continue
    locs[loc] = locs.get(loc, 0) + 1
lines = ["; generated by tools/gen_dragon_places.py from Skyrim.esm - do not edit",
         f"; {len(walls)} WordWallTrigger refs, {len(locs)} locations kept ({unplaced} refs without a cell location)",
         "[word_walls]   ; location FormID = word-wall refs there"]
for loc in sorted(locs):
    lines.append(f"{loc:X} = {locs[loc]}   ; {loc_name.get(loc, '?')}")
open(out, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
print(f"wrote {out}: {len(locs)} word-wall locations from {len(walls)} refs ({unplaced} unplaced)")
