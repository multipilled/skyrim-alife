"""config/positions.ltx: world positions for vanilla locations that have no world marker reference (Solitude, Falkreath ...),
taken from the centroid of their exterior cells in the user's Skyrim.esm (see dump_world.py)."""
import json, os
here = os.path.dirname(os.path.abspath(__file__))
d = json.load(open(os.path.join(here, "..", "..", "data", "world_skyrim.json")))
rows = []
for L in d["locations"]:
    if L["root_world"] != 0x3C or L.get("source_pos") != "cells": continue
    if 0x16771 in L["keywords"]: continue          # hold regions are not places
    rows.append((L["formid"], L["x"], L["y"], L["edid"].replace("Location", "")))
rows.sort()
out = ["; Positions of vanilla locations without a world marker reference (Skyrim.esm FormID = x, y). Generated by tools/gen_positions.py.", "[pos]"]
for fid, x, y, n in rows: out.append(f"{fid:X} = {x:.0f}, {y:.0f}   ; {n}")
open(os.path.join(here, "..", "config", "positions.ltx"), "w", newline="\n").write("\n".join(out) + "\n")
print(len(rows), "positions")
