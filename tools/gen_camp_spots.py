"""config/camp_spots.ltx: the Skyrim.esm base forms camp life (docs/CAMPLIFE.md, M5h) looks for around a place: lit and unlit
campfires, beds and bedrolls, seats, lean / wall markers and cooking spots. Read only from the user's Skyrim.esm (fastscan);
the plugin matches placed refs by base FormID (EditorIDs are not loaded at runtime).
usage: python -I tools/gen_camp_spots.py [path to Skyrim.esm]"""
import os
import re
import struct
import sys

here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(here, "esp"))
import fastscan as fs  # noqa: E402

ESM = sys.argv[1] if len(sys.argv) > 1 else r"C:\Program Files (x86)\Steam\steamapps\common\Skyrim Special Edition\Data\Skyrim.esm"
res = fs.scan(ESM, {"KYWD", "FURN", "STAT", "MSTT", "LIGH"})
kw = {fid: fs.edid(s) for fid, fl, s in res.get("KYWD", [])}


def keywords(s):
    v = fs.get(s, "KWDA") or b""
    return {kw.get(struct.unpack_from("<I", v, i)[0], "") for i in range(0, len(v), 4)}


spots = {k: [] for k in ("campfire", "campfire_unlit", "bed", "seat", "lean", "cook")}
for fid, fl, s in res.get("MSTT", []) + res.get("LIGH", []):
    e = fs.edid(s)
    if re.search(r"(?i)campfire", e) and re.search(r"(?i)burning|^LightCampFire", e) and not e.startswith("Test"):
        spots["campfire"].append((fid, e))
for fid, fl, s in res.get("STAT", []):
    e = fs.edid(s)
    if re.search(r"(?i)campfire\d*Land(Off|Burning)?", e) and "Off" in e:
        spots["campfire_unlit"].append((fid, e))
for fid, fl, s in res.get("FURN", []):
    e, k = fs.edid(s), keywords(s)
    if e.startswith("Test"):
        continue
    if "FurnitureBedRoll" in k or (re.search(r"Bed(roll|Single|Double|Bunk)?", e) and "Child" not in e and "bench" not in e.lower()):
        spots["bed"].append((fid, e))
    elif "CraftingCookpot" in k or e.startswith("CraftingCookingFireSpit"):
        spots["cook"].append((fid, e))
    elif "FurnitureCounterLeanMarker" in k or re.search(r"LeanMarker|SoldierWallIdle", e):
        spots["lean"].append((fid, e))
    elif (re.search(r"Chair|Bench|Stool", e) or "FurnitureLedgeSit" in k) and not re.search(r"Throne|Workbench|Crafting|Child|Player|Jarl", e):
        spots["seat"].append((fid, e))

out = ["; Camp life spots (docs/CAMPLIFE.md): Skyrim.esm base forms by kind. Generated by tools/gen_camp_spots.py from the user's",
       "; Skyrim.esm (read only): edit the generator, not this file. Values are Skyrim.esm FormIDs (hex, no load index).",
       "[spots]"]
for k, rows in spots.items():
    rows.sort()
    out.append(f"; {k}: {len(rows)} ({', '.join(e for _, e in rows[:6])}{', ...' if len(rows) > 6 else ''})")
    out.append(f"{k} = " + ", ".join(f"{fid & 0xFFFFFF:X}" for fid, _ in rows))
path = os.path.join(here, "..", "config", "camp_spots.ltx")
open(path, "w", newline="\n").write("\n".join(out) + "\n")
print(" ".join(f"{k}={len(v)}" for k, v in spots.items()), "->", os.path.normpath(path))
